#!/usr/bin/env bash
# =============================================================================
# ERP 모집단 자동 추출 도구 — 서버 실행 스크립트
# =============================================================================
#
# [비개발자를 위한 사용법]
# 1. 이 파일(run.sh)이 들어있는 폴더에서 터미널(명령 프롬프트/Terminal)을 엽니다.
# 2. 아래 한 줄을 그대로 입력하고 Enter를 누릅니다.
#
#      bash run.sh
#
# 3. 화면에 여러 줄의 메시지가 지나가다가 마지막에
#      Uvicorn running on http://0.0.0.0:8000
#    비슷한 메시지가 뜨고, 커서가 깜빡이며 "멈춘 것처럼" 보입니다.
#    -> 이것은 오류가 아니라 정상입니다. 프로그램이 "계속 켜진 채로 대기 중"이라는
#       뜻입니다. 이 터미널 창을 닫지 마세요.
# 4. 이 상태에서 웹 브라우저(크롬 등)를 새로 열고, 주소창에 아래 주소를 입력합니다.
#
#      http://localhost:8000
#
#    화면에 스타일(디자인)이 입혀진 정상적인 화면이 나오면 성공입니다.
#    ("index.html 파일을 더블클릭"해서 여는 것과는 다릅니다 — 반드시 이 스크립트로
#     서버를 먼저 켠 뒤, 브라우저 주소창에 주소를 입력해서 접속해야 합니다.)
# 5. 사용을 마치면 터미널 창에서 Ctrl+C를 눌러 서버를 끕니다.
#
# [중요] 이 서버가 켜주는 것은 "웹 화면 + 엑셀 처리 로직"입니다. SAP 자동화
# (SAP GUI Scripting) 기능은 Windows에 SAP Logon이 설치되고 로그인되어 있는
# PC에서만 동작합니다. 이 서버를 GCP/클라우드 서버에서 켜도 SAP 조회 자체는
# 되지 않으며, 대신 "__mock__" 세션으로 나머지 파이프라인(편집규칙 → 담당자매칭
# → 검증 → 표본추출 → 결과엑셀)을 확인할 수 있습니다. 자세한 내용은
# docs/HANDOFF.md 상단의 표를 참고하세요.
# =============================================================================

set -e

# 이 스크립트가 있는 폴더로 이동한다 (터미널을 어느 위치에서 열었든 항상 저장소
# 루트 기준으로 동작하게 하기 위함).
cd "$(dirname "${BASH_SOURCE[0]}")"

# python3 명령이 있으면 그것을, 없으면 python 명령을 사용한다.
if command -v python3 >/dev/null 2>&1; then
  PYTHON=python3
elif command -v python >/dev/null 2>&1; then
  PYTHON=python
else
  echo "[오류] python이 설치되어 있지 않습니다. Python 3.10 이상을 먼저 설치한 뒤 다시 실행하세요." >&2
  exit 1
fi

echo "[1/2] 필요한 패키지를 설치합니다 (처음 실행할 때만 몇 분 걸릴 수 있습니다)..."
"$PYTHON" -m pip install --quiet -r requirements.txt

echo ""
echo "[2/2] 서버를 실행합니다."
echo "      아래에 'Uvicorn running on ...' 메시지가 뜨면 정상입니다."
echo "      이 터미널 창은 그대로 두고, 웹 브라우저에서 http://localhost:8000 을 여세요."
echo "      (GCP Vertex AI Workbench 등 원격 서버에서 실행 중이라면, 8000번 포트를"
echo "       브라우저로 전달(포트포워딩/웹 프리뷰)해야 접속할 수 있습니다.)"
echo "      끝내려면 이 창에서 Ctrl+C를 누르세요."
echo ""

PYTHONPATH=src exec "$PYTHON" -m uvicorn web.backend:app --host 0.0.0.0 --port 8000
