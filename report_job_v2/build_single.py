"""Build the single-file distribution from maintained source modules."""
from pathlib import Path
import json

root = Path(__file__).resolve().parent
header = '''# Generated by build_single.py. Edit the separate source modules, not this file.
# Python 3.10+; dependency: openpyxl==3.1.5
import sys as _sys
import types as _types
'''
parts = [header]
for name in ("report_analyzer", "report_ui"):
    source = (root / (name + ".py")).read_text(encoding="utf-8")
    parts.append(f"\n_m = _types.ModuleType({name!r})\n_m.__file__ = __file__\n_sys.modules[{name!r}] = _m\nexec(compile({source!r}, __file__ + ':{name}', 'exec'), _m.__dict__)\n")
# The future import must remain at the start of a compilation unit.
engine = (root / "report_job_v2.py").read_text(encoding="utf-8")
parts.append(f"\nexec(compile({engine!r}, __file__ + ':engine', 'exec'), globals())\n")
(root / "report_job_v2_single.py").write_text("".join(parts), encoding="utf-8")
print("Built report_job_v2_single.py")
